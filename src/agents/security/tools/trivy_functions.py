import subprocess
import json
import os
from helpers.deduplicators.deduplicator_trivy import dedupe
from strands import tool

# -------------------------
# RUNNER FUNCTION
# -------------------------
def run_trivy_scan(repo_path: str, output_file: str) -> list | None:
    try:
        if os.path.exists(output_file):
            os.remove(output_file)

        subprocess.run(
            [
                "trivy",
                "fs",
                repo_path,
                "--scanners", "secret",
                "--format", "json",
                "-o", output_file,
                "--quiet",
                "--no-progress"
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            timeout=250
        )

        if not os.path.exists(output_file):
            return [{
                "type": "TrivyError",
                "message": "Trivy did not generate output file",
                "details": None
            }]

        if os.path.getsize(output_file) == 0:
            return [{
                "type": "TrivyError",
                "message": "Trivy generated empty report",
                "details": None
            }]

        return None

    except subprocess.TimeoutExpired:
        return [{
            "type": "TrivyError",
            "message": "Timeout during Trivy execution",
            "details": None
        }]

    except subprocess.CalledProcessError as e:
        return {
            "type": "TrivyError",
            "message": "Trivy execution failed",
            "details": (e.stderr or b"").decode()
        }


# -------------------------
# PARSER FUNCTION
# -------------------------
def parse_trivy_report(output_file: str) -> dict:
    if not os.path.exists(output_file):
        return {"error_obj": {"type": "TrivyParseError", "message": "Report file was not generated.", "details": None}}

    try:
        with open(output_file, 'r', encoding='utf-8') as f:
            content = f.read().strip()
            full_data = json.loads(content) if content else {"Results": []}
    except json.JSONDecodeError:
        return {"error_obj": {"type": "TrivyParseError", "message": "Invalid JSON file generated by Trivy", "details": None}}

    critical_findings = []
    high_findings = []
    medium_findings = []

    for item in full_data.get("Results", []):
        target = item.get("Target") or "unknown"

        if item.get("Class") != "secret":
            continue

        secrets = item.get("Secrets") or []
        if not secrets:
            continue

        for secret in secrets: 
            severity = secret.get("Severity")
            if severity not in {"CRITICAL", "HIGH", "MEDIUM"}:
                continue

            finding = {
                "rule_id": secret.get("RuleID"),
                "path": target or "unknown",
                "line": secret.get("StartLine", -1),
                "description": (secret.get("Title") or secret.get("RuleID") or ""),
                "severity": severity,
                "secret_category": secret.get("Category"),
                "remediation": None
            }

            if severity == "CRITICAL":
                critical_findings.append(finding)
            elif severity == "HIGH":
                high_findings.append(finding)
            elif severity == "MEDIUM":
                medium_findings.append(finding)
    
    critical_findings = dedupe(critical_findings)
    high_findings = dedupe(high_findings)
    medium_findings = dedupe(medium_findings)

    findings_for_agent = []

    if len(critical_findings) >= 10:
        findings_for_agent = critical_findings[:10]

    elif len(critical_findings) > 0:
        needed = 10 - len(critical_findings)
        findings_for_agent = (
            critical_findings +
            high_findings[:needed]
        )

        if len(findings_for_agent) < 5:
            remaining = 5 - len(findings_for_agent)
            findings_for_agent += medium_findings[:remaining]

    elif len(high_findings) < 5:
        needed = 5 - len(high_findings)
        findings_for_agent = (
            high_findings + 
            medium_findings[:needed]
        )

    else:
        findings_for_agent = high_findings[:10]

    return {
        "findings_to_analyze": findings_for_agent
    }


# -------------------------
# STRANDS AGENT TOOL
# -------------------------
@tool
def run_trivy(repo_path: str) -> dict:
    """
    Run Trivy scan on a repository and return summarized secret findings.

    When to use:
    - Use this tool when you need to detect secrets in filesystem contents.
    - Especially useful for identifying high and critical severity secret leaks across repository files.

    Args:
        repo_path (str): Absolute path to the repository to scan.

    Returns:
        dict: A structured result containing:
            - "status": "success" or "error"
            - "findings_to_analyze": list of detected issues with:
                "rule_id": id of the secret rule,
                "path": path of the finding,
                "line": starting line of the finding,
                "description": description of the finding,
                "severity": severity of the finding,
                "secret_category": type of secret in the finding,
                "remediation": Empty field you have to fill
            - "errors": list of errors (empty list on success, execution or parsing error on failure).
              Every error object always has exactly these three fields:
                "type": one of "TrivyError", "TrivyParseError", or a Trivy internal type,
                "message": human-readable description of the error,
                "details": additional context string, or null if not available
    """

    output_file = "raw_trivy_report.json"

    scan_errors = run_trivy_scan(repo_path, output_file)
    if scan_errors:
        return {
            "status": "error",
            "findings_to_analyze": [],
            "errors": scan_errors
        }

    result = parse_trivy_report(output_file)

    if "error_obj" in result:
        return {
            "status": "error",
            "findings_to_analyze": [],
            "errors": [result["error_obj"]]
        }

    return {
        "status": "success",
        "findings_to_analyze": result.get("findings_to_analyze", []),
        "errors": [],
    }
