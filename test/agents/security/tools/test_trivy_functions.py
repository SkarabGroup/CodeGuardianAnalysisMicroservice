import os
import json
import subprocess
from unittest.mock import patch
from src.agents.security.tools.trivy_functions import (
    parse_trivy_report,
    run_trivy_scan,
    run_trivy,
)

FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "fixtures")


def get_fixture_path(name):
    return os.path.join(FIXTURES_DIR, name)


# -------------------------
# PARSER TESTS
# -------------------------

def test_parser_valid():
    result = parse_trivy_report(get_fixture_path("trivy_valid.json"))

    assert len(result["findings_to_analyze"]) == 1
    finding = result["findings_to_analyze"][0]

    assert finding["rule_id"] == "private-key"
    assert finding["severity"] == "HIGH"
    assert finding["category"] == "AsymmetricPrivateKey"


def test_parser_empty():
    result = parse_trivy_report(get_fixture_path("trivy_empty.json"))

    assert result["findings_to_analyze"] == []


def test_parser_no_secrets():
    result = parse_trivy_report(get_fixture_path("trivy_no_secrets.json"))

    assert result["findings_to_analyze"] == []


def test_parser_low_severity_filtered():
    result = parse_trivy_report(get_fixture_path("trivy_low_severity.json"))

    assert result["findings_to_analyze"] == []


def test_parser_file_not_found():
    result = parse_trivy_report("nonexistent.json")

    assert "error" in result


def test_parser_invalid_json(tmp_path):
    file = tmp_path / "bad.json"
    file.write_text("not json")

    result = parse_trivy_report(str(file))

    assert "error" in result

def test_parser_skips_non_secret_class(tmp_path):
    result = parse_trivy_report(get_fixture_path("trivy_non_secret.json"))

    assert result["findings_to_analyze"] == []


