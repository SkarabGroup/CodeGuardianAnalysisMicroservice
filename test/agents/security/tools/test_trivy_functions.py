@patch("subprocess.run")
def test_run_trivy_success(mock_run, tmp_path):
    output_file = tmp_path / "report.json"

    def fake_run(*args, **kwargs):
        output_file.write_text('{"Results": []}')
        return None

    mock_run.side_effect = fake_run

    error = run_trivy_scan("repo", str(output_file))

    assert error is None


@patch("subprocess.run")
def test_run_trivy_timeout(mock_run):
    mock_run.side_effect = subprocess.TimeoutExpired("cmd", 10)

    error = run_trivy_scan("repo", "out.json")

    assert "Timeout" in error["error"]


@patch("subprocess.run")
def test_run_trivy_failure(mock_run):
    mock_run.side_effect = subprocess.CalledProcessError(1, "cmd", stderr=b"fail")

    error = run_trivy_scan("repo", "out.json")

    assert "error" in error
    assert "details" in error


@patch("subprocess.run")
def test_run_trivy_no_file(mock_run):
    mock_run.return_value = None 

    error = run_trivy_scan("repo", "nonexistent.json")

    assert "error" in error

@patch("subprocess.run")
def test_run_trivy_empty_file(mock_run, tmp_path):
    output_file = tmp_path / "report.json"

    def fake_run(*args, **kwargs):
        output_file.write_text("")

    mock_run.side_effect = fake_run

    error = run_trivy_scan("repo", str(output_file))

    assert "error" in error

@patch("subprocess.run")
@patch("os.remove")
def test_run_trivy_removes_existing_file(mock_remove, mock_run, tmp_path):
    output_file = tmp_path / "report.json"

    output_file.write_text("old content")

    def fake_run(*args, **kwargs):
        output_file.write_text('{"Results": []}')

    mock_run.side_effect = fake_run

    error = run_trivy_scan("repo", str(output_file))

    assert error is None
    mock_remove.assert_called_once()


